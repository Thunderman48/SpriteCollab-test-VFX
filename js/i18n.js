/** Korean topic particle 은/는 for the last syllable of a word. */
function eun(word) {
  const c = String(word).replace(/<[^>]*>/g, '').trim().slice(-1).charCodeAt(0);
  if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28 ? '은' : '는';
  return '은(는)';
}

